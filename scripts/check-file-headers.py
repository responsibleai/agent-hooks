"""Fail when a tracked source file lacks the standard file header.

Every hand-written source file starts with the one-line notice held in
``HEADER_TEXT`` below, in the language's line-comment style, followed by
a blank line. A shebang line may come
first. Generated and vendored files are listed in ``SKIP``.

Usage: ``python3 scripts/check-file-headers.py [path ...]``. With no
paths, every tracked file with a known extension is checked. Exit status
1 lists the offending files on stderr.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

HEADER = "Copyright (c) Microsoft. All rights reserved."
PREFIXES = {
    ".py": "#",
    ".pyi": "#",
    ".sh": "#",
    ".rs": "//",
    ".ts": "//",
    ".mts": "//",
    ".mjs": "//",
    ".js": "//",
    ".cs": "//",
    ".go": "//",
    ".h": "//",
}
SKIP = {
    # Generated by napi-rs on every build; the drift gate in ci.yml
    # forbids hand edits.
    "sdk/typescript/binding.js",
    "sdk/typescript/binding.d.ts",
    # Vendored from serde_jcs; keeps the upstream attribution notice
    # (THIRD-PARTY-NOTICES.md).
    "sdk/rust/core/src/jcs.rs",
}
ROOT = Path(__file__).resolve().parent.parent


def tracked_files() -> list[str]:
    out = subprocess.run(
        ["git", "ls-files", "-z"], cwd=ROOT, check=True, capture_output=True
    ).stdout
    return [p for p in out.decode("utf-8").split("\0") if p]


def problem(path: Path, prefix: str) -> str | None:
    try:
        text = path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        return "not UTF-8"
    lines = text.removeprefix("﻿").split("\n")
    if lines and lines[0].startswith("#!"):
        lines = lines[1:]
    expected = f"{prefix} {HEADER}"
    if not lines or lines[0] != expected:
        return f"first line is not {expected!r}"
    # A file that is only the header line ends here.
    if len(lines) > 1 and lines[1] != "":
        return "no blank line after the header"
    for number, line in enumerate(lines[1:6], start=2):
        if "Copyright" in line or "Licensed under" in line:
            return f"a second header line on line {number}"
    return None


def main(argv: list[str]) -> int:
    if len(argv) > 1:
        candidates = []
        for arg in argv[1:]:
            try:
                candidates.append(Path(arg).resolve().relative_to(ROOT).as_posix())
            except ValueError:
                print(f"{arg}: outside the repository", file=sys.stderr)
                return 2
    else:
        candidates = tracked_files()

    checked = 0
    failures = []
    for rel in candidates:
        prefix = PREFIXES.get(Path(rel).suffix)
        if prefix is None or rel in SKIP:
            continue
        checked += 1
        why = problem(ROOT / rel, prefix)
        if why is not None:
            failures.append(f"{rel}: {why}")

    for failure in failures:
        print(failure, file=sys.stderr)
    print(f"check-file-headers: {checked} files checked, {len(failures)} failing")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
